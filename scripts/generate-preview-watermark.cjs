// Compile the repository's Geist font into SVG paths once. Runtime needs no fonts.
const fs = require('node:fs');
const path = require('node:path');
const opentype = require('opentype.js');
const root = path.resolve(__dirname, '..');
const fontBytes = fs.readFileSync(path.join(root, 'src/app/fonts/GeistVF.woff'));
const font = opentype.parse(fontBytes.buffer.slice(fontBytes.byteOffset, fontBytes.byteOffset + fontBytes.byteLength));
const title = 'OldPhotoLive AI · PREVIEW';
const textPath = font.getPath(title, 0, 0, 27);
const box = textPath.getBoundingBox();
const offsetX = (600 - (box.x2 - box.x1)) / 2 - box.x1;
const offsetY = (64 - (box.y2 - box.y1)) / 2 - box.y1;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="64" viewBox="0 0 600 64"><rect width="600" height="64" rx="10" fill="#111827" fill-opacity="0.48"/><path d="${textPath.toPathData(2)}" transform="translate(${offsetX.toFixed(2)} ${offsetY.toFixed(2)})" fill="#ffffff" fill-opacity="0.88"/></svg>`;
fs.writeFileSync(path.join(root, 'src/lib/preview-watermark-svg.ts'), `// Generated by scripts/generate-preview-watermark.cjs from the bundled Geist font.\n// Fixed paths keep preview labels identical without runtime font dependencies.\nexport const PREVIEW_WATERMARK_SVG = ${JSON.stringify(svg)};\n`);
